/**
 * Copies the on-device ADB helper APK (built by `:helper`) into a Compose
 * resources directory and generates `AdbHelperArtifact` with its SHA-256, so
 * the desktop/web clients can tell whether the copy on a device is current,
 * and the lowest SDK it runs on.
 */
abstract class PrepareAdbHelper : DefaultTask() {
    @get:InputFiles
    abstract val apkDirectory: ConfigurableFileCollection

    @get:Input
    abstract val minSdk: Property<Int>

    @get:OutputDirectory
    abstract val resourcesDirectory: DirectoryProperty

    @get:OutputDirectory
    abstract val sourcesDirectory: DirectoryProperty

    @TaskAction
    fun prepare() {
        val apk = apkDirectory.asFileTree.matching { include("*.apk") }.singleFile
        val bytes = apk.readBytes()
        val sha256 = MessageDigest.getInstance("SHA-256").digest(bytes)
            .joinToString("") { "%02x".format(it) }

        resourcesDirectory.get().asFile.resolve("files").apply {
            deleteRecursively()
            mkdirs()
            resolve("canta-helper.apk").writeBytes(bytes)
        }
        sourcesDirectory.get().asFile.resolve("io/github/samolego/canta/core/adb").apply {
            deleteRecursively()
            mkdirs()
            resolve("AdbHelperArtifact.kt").writeText(
                """
                |// Generated by the prepareAdbHelper task. Do not edit.
                |package io.github.samolego.canta.core.adb
                |
                |internal object AdbHelperArtifact {
                |    /** Compose resource path of the bundled helper APK. */
                |    const val RESOURCE_PATH = "files/canta-helper.apk"
                |    const val SHA256 = "$sha256"
                |    /** Devices on older Android versions are refused. */
                |    const val MIN_SDK = ${minSdk.get()}
                |}
                |""".trimMargin()
            )
        }
    }
}

/** Generates `BuildInfo` with the app version from `gradle.properties`, for every target. */
@CacheableTask
abstract class GenerateBuildInfo : DefaultTask() {
    @get:Input
    abstract val versionName: Property<String>

    @get:Input
    abstract val versionCode: Property<Int>

    @get:Input
    abstract val developmentBuildNumber: Property<Int>

    @get:OutputDirectory
    abstract val sourcesDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        sourcesDirectory.get().asFile.resolve("io/github/samolego/canta").apply {
            deleteRecursively()
            mkdirs()
            resolve("BuildInfo.kt").writeText(
                """
                |// Generated by the generateBuildInfo task. Do not edit.
                |package io.github.samolego.canta
                |
                |object BuildInfo {
                |    const val VERSION_NAME = "${versionName.get()}"
                |    const val VERSION_CODE = ${versionCode.get()}
                |    const val DEVELOPMENT_BUILD_NUMBER = ${developmentBuildNumber.get()}
                |}
                |""".trimMargin()
            )
        }
    }
}

/** Generates `BuildFlags`, so debug-only code is a compile-time constant that release builds can drop. */
@CacheableTask
abstract class GenerateBuildFlags : DefaultTask() {
    @get:Input
    abstract val debug: Property<Boolean>

    /** Where the anonymous package-safety telemetry goes; see util/TelemetryConfig.kt. */
    @get:Input
    abstract val telemetryBaseUrl: Property<String>

    @get:Input
    abstract val telemetryApiKey: Property<String>

    @get:OutputDirectory
    abstract val sourcesDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        sourcesDirectory.get().asFile.resolve("io/github/samolego/canta").apply {
            deleteRecursively()
            mkdirs()
            resolve("BuildFlags.kt").writeText(
                """
                |// Generated by the generateBuildFlags task. Do not edit.
                |package io.github.samolego.canta
                |
                |object BuildFlags {
                |    /** Debug-only features (fake community scores) are shown only when true. */
                |    const val IS_DEBUG = ${debug.get()}
                |}
                |""".trimMargin()
            )
            resolve("TelemetryEndpoints.kt").writeText(
                """
                |// Generated by the generateBuildFlags task. Do not edit.
                |package io.github.samolego.canta
                |
                |/**
                | * Where telemetry goes, so a build can point at another backend without a code change:
                | * `-Pcanta.telemetry.baseUrl=... -Pcanta.telemetry.apiKey=...`
                | */
                |object TelemetryEndpoints {
                |    const val BASE_URL = "${telemetryBaseUrl.get()}"
                |    const val API_KEY = "${telemetryApiKey.get()}"
                |}
                |""".trimMargin()
            )
        }
    }
}

val generateBuildInfo = tasks.register<GenerateBuildInfo>("generateBuildInfo") {
    versionName.set(providers.gradleProperty("version_name"))
    versionCode.set(providers.gradleProperty("version_code").map(String::toInt))
    developmentBuildNumber.set(
        providers.environmentVariable("CANTA_DEVELOPMENT_BUILD_NUMBER")
            .map { it.toIntOrNull() ?: 0 }
            .orElse(0)
    )
    sourcesDirectory.set(layout.buildDirectory.dir("generated/buildInfo/kotlin"))
}

// `-Pcanta.debug=true|false` wins. Otherwise it is a debug build when any requested task is a
// debug variant, a desktop dev run (`run`, hot reload) or a wasm development build; release
// and plain `build` / `test` invocations are not.
val generateBuildFlags = tasks.register<GenerateBuildFlags>("generateBuildFlags") {
    // Defaults are our own Supabase project; the publishable key is meant to be embedded in
    // clients, so it can stay here. Override with -Pcanta.telemetry.baseUrl / .apiKey.
    telemetryBaseUrl.set(
        providers.gradleProperty("canta.telemetry.baseUrl")
            .orElse("https://axuhfogeovtsbxokqccf.supabase.co/rest/v1/rpc/")
    )
    telemetryApiKey.set(
        providers.gradleProperty("canta.telemetry.apiKey")
            .orElse("sb_publishable_YipHHrFaw1E2q5qTUVPl0A_plD7Q5yS")
    )
    val requestedTasks = gradle.startParameter.taskNames
    debug.set(
        providers.gradleProperty("canta.debug").map { it.toBoolean() }.orElse(
            providers.provider {
                requestedTasks.any { requested ->
                    val name = requested.substringAfterLast(':')
                    name.contains("debug", ignoreCase = true) ||
                        name.contains("development", ignoreCase = true) ||
                        name.startsWith("hotRun", ignoreCase = true) ||
                        name == "run"
                }
            }
        )
    )
    sourcesDirectory.set(layout.buildDirectory.dir("generated/buildFlags/kotlin"))
}

