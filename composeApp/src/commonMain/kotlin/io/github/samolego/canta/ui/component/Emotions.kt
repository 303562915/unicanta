/**
 * One sticker of the comment bar: the name it travels under, and the picture it stands for.
 *
 * A comment carries stickers as text — "[偷笑]" — because the backend stores a body string and
 * nothing else, and because that is what a copied comment has to read as. The name is what
 * travels; [resource] is what is drawn, in the picker and inline in the comment itself.
 *
 * [key] is the file the sticker came in as. It is kept because two stickers may end up sharing a
