/** The stickers by name: how a "[偷笑]" in a comment body finds its picture. */
private val BY_NAME: Map<String, Emotion> = EMOTIONS.associateBy { it.name }

/** The stickers by file key, for a body written before names were what a comment carried. */
private val BY_KEY: Map<String, Emotion> = EMOTIONS.associateBy { it.key }

/**
 * The sticker a token names, or null for a bracket that is just text somebody typed.
 *
 * The name is asked first — that is what the picker inserts now — and the file key second, so a
 * comment written while the tokens were still pinyin keeps rendering instead of turning into
 * visible syntax.
 */
fun emotionOf(nameOrKey: String): Emotion? = BY_NAME[nameOrKey] ?: BY_KEY[nameOrKey]

private val INLINE_DP = 17

/** The side one sticker is drawn at inside a comment, in dp: the line it sits on is 19sp. */
val EmotionInlineSize = INLINE_DP.dp

/** The same side as a text unit: an inline placeholder is measured like a character. */
val EmotionInlineSizeSp = INLINE_DP.sp
